-- 2. plan_case 增加计划日期列并回填（execute_time 可为空，不能直接作分区键）
ALTER TABLE `plan_case`
  ADD COLUMN `plan_date` date NOT NULL DEFAULT '1970-01-01'
  COMMENT '计划日期（版本计划创建时间对应日期，分区键）' AFTER `plan_id`;

UPDATE `plan_case` pc
JOIN `version_plan` vp ON vp.`id` = pc.`plan_id`
SET pc.`plan_date` = DATE(FROM_UNIXTIME(vp.`create_time` / 1000));

-- 分区键必须包含在主键中：主键调整为 (id, plan_date)
